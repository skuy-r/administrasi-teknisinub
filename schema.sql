-- Jalankan di Supabase Dashboard > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'teknisi' check (role in ('admin','teknisi')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.repairs (
  id bigint generated by default as identity primary key,
  req_no text not null unique,
  req_date date not null default current_date,
  asset text not null,
  location text not null,
  damage text not null,
  condition text not null,
  steps text not null default '',
  finish_date date,
  status text not null default 'Menunggu' check(status in ('Menunggu','Diproses','Selesai','Dibatalkan')),
  created_by text not null,
  tech_name text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.parts (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  spec text not null default '',
  unit text not null default 'pcs',
  min_stock integer not null default 0 check(min_stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.movements (
  id bigint generated by default as identity primary key,
  part_id bigint not null references public.parts(id),
  move_date date not null default current_date,
  kind text not null check(kind in ('MASUK','KELUAR')),
  qty integer not null check(qty > 0),
  repair_id bigint references public.repairs(id) on delete set null,
  taken_by text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.repair_parts (
  id bigint generated by default as identity primary key,
  repair_id bigint not null references public.repairs(id) on delete cascade,
  part_id bigint not null references public.parts(id),
  qty integer not null check(qty > 0),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name,role,active)
  values(new.id, coalesce(new.raw_user_meta_data->>'full_name','Pengguna'), 'teknisi', true)
  on conflict(id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.current_role()
returns text language sql stable security definer set search_path=public as $$
  select role from public.profiles where id=auth.uid() and active=true
$$;
create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and active=true)
$$;

alter table public.profiles enable row level security;
alter table public.repairs enable row level security;
alter table public.parts enable row level security;
alter table public.movements enable row level security;
alter table public.repair_parts enable row level security;

-- Profiles: users can see their own profile; admins can see/manage profiles.
create policy "profile read own or admin" on public.profiles for select to authenticated
using (id=auth.uid() or public.current_role()='admin');
create policy "profile admin update" on public.profiles for update to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');

-- Signed-in active staff can read operational data. Only active staff can write.
create policy "repairs read active" on public.repairs for select to authenticated using (public.is_active_user());
create policy "repairs insert active" on public.repairs for insert to authenticated with check (public.is_active_user());
create policy "repairs update staff" on public.repairs for update to authenticated using (public.is_active_user()) with check (public.is_active_user());
create policy "parts read active" on public.parts for select to authenticated using (public.is_active_user());
create policy "parts admin insert" on public.parts for insert to authenticated with check (public.current_role()='admin');
create policy "parts admin update" on public.parts for update to authenticated using (public.current_role()='admin') with check (public.current_role()='admin');
create policy "moves read active" on public.movements for select to authenticated using (public.is_active_user());
create policy "moves insert staff" on public.movements for insert to authenticated with check (public.is_active_user());
create policy "repair parts read active" on public.repair_parts for select to authenticated using (public.is_active_user());
create policy "repair parts insert staff" on public.repair_parts for insert to authenticated with check (public.is_active_user());

grant usage on schema public to authenticated;
grant select,update on public.profiles to authenticated;
grant select,insert,update on public.repairs to authenticated;
grant select,insert,update on public.parts to authenticated;
grant select,insert on public.movements to authenticated;
grant select,insert on public.repair_parts to authenticated;

